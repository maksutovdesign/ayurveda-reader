// IAST → русская академическая транслитерация санскрита (с диакритикой).
// Конвенция: долгие гласные — макрон (а̄, ӣ, ӯ); церебральные — точка снизу
// (т̣, д̣, н̣, ш̣, р̣); палатальные — ш́ (ś), н̃ (ñ); анусвара — м̣; висарга — х̣.

const MAC = '̄';   // ◌̄  макрон
const DOT = '̣';   // ◌̣  точка снизу (церебральные)
const DOTA = '̇';  // ◌̇  точка сверху (ṅ)
const TIL = '̃';   // ◌̃  тильда (ñ)
const ACU = '́';   // ◌́  акут (ś)

// Диграфы-придыхательные — проверяются раньше одиночных букв.
const DIGRAPHS = {
  'kh': 'кх', 'gh': 'гх', 'ch': 'чх', 'jh': 'джх',
  'ṭh': 'т̣х', 'ḍh': 'д̣х', 'th': 'тх', 'dh': 'дх',
  'ph': 'пх', 'bh': 'бх',
};

const SINGLES = {
  // гласные
  'a': 'а', 'ā': 'а' + MAC,
  'i': 'и', 'ī': 'ӣ',
  'u': 'у', 'ū': 'ӯ',
  'ṛ': 'р' + DOT, 'ṝ': 'р' + DOT + MAC,
  'ḷ': 'л' + DOT, 'ḹ': 'л' + DOT + MAC,
  'e': 'е', 'ē': 'е',
  'o': 'о', 'ō': 'о',
  // согласные
  'k': 'к', 'g': 'г', 'ṅ': 'н' + DOTA,
  'c': 'ч', 'j': 'дж', 'ñ': 'н' + TIL,
  'ṭ': 'т' + DOT, 'ḍ': 'д' + DOT, 'ṇ': 'н' + DOT,
  't': 'т', 'd': 'д', 'n': 'н',
  'p': 'п', 'b': 'б', 'm': 'м',
  'y': 'й', 'r': 'р', 'l': 'л', 'v': 'в',
  'ś': 'ш' + ACU, 'ṣ': 'ш' + DOT, 's': 'с', 'h': 'х',
  // анусвара / висарга / чандрабинду
  'ṃ': 'м' + DOT, 'ṁ': 'м' + DOT, 'ḥ': 'х' + DOT, 'ँ': 'м' + DOT,
  // OCR-варианты и заглушки
  'ṟ': 'р', 'ï': 'и', 'î': 'и', 'é': 'е', 'á': 'а', 'í': 'и',
};

// Заглавные — берём отображение строчной и поднимаем первую базовую букву.
const CAPS = {
  'Ā': 'А' + MAC, 'Ī': 'Ӣ', 'Ū': 'Ӯ',
  'Ś': 'Ш' + ACU, 'Ṣ': 'Ш' + DOT, 'Ṇ': 'Н' + DOT, 'Ṭ': 'Т' + DOT, 'Ḍ': 'Д' + DOT,
  'A': 'А', 'Á': 'А', 'I': 'И', 'Í': 'И', 'U': 'У',
  'K': 'К', 'G': 'Г', 'C': 'Ч', 'J': 'Дж', 'T': 'Т', 'D': 'Д', 'N': 'Н',
  'P': 'П', 'B': 'Б', 'M': 'М', 'Y': 'Й', 'R': 'Р', 'L': 'Л', 'V': 'В',
  'S': 'С', 'H': 'Х', 'E': 'Е', 'O': 'О',
};

export function iastToCyrillic(input) {
  if (!input) return input;
  // 1. NFC собирает разложённые диакритики (a+макрон→ā, m+точка→ṁ, …).
  let s = input.normalize('NFC');
  // 2. Слоговые r/l через «кольцо снизу» (U+0325) → церебральные ṛ/ḷ.
  s = s.replace(/r̥/g, 'ṛ').replace(/l̥/g, 'ḷ');
  // 3. Прочие висячие комбинирующие знаки убираем.
  s = s.replace(/[̥]/g, '');

  const chars = [...s];
  let out = '';
  for (let i = 0; i < chars.length; i++) {
    const two = chars[i] + (chars[i + 1] || '');
    if (DIGRAPHS[two]) { out += DIGRAPHS[two]; i++; continue; }
    const c = chars[i];
    if (SINGLES[c] != null) { out += SINGLES[c]; continue; }
    if (CAPS[c] != null) { out += CAPS[c]; continue; }
    out += c; // апострофы, кавычки, пробелы, неизвестное — как есть
  }
  return out;
}

// Запуск напрямую: node scripts/iast-to-cyrillic.mjs "текст"
if (import.meta.url === `file://${process.argv[1]}`) {
  const arg = process.argv.slice(2).join(' ');
  if (arg) console.log(iastToCyrillic(arg));
}
